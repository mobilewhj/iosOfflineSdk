#!/usr/bin/env python3
"""生成隔离托管 A/B 包；默认保留历史 demo.zip 与 PackageDigest.h。"""
from pathlib import Path
import argparse
import hashlib
import json
import zipfile

ROOT = Path(__file__).resolve().parents[1]

def archive(source, target):
    target.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(target, 'w') as output:
        for path in sorted(source.rglob('*')):
            if not path.is_file():
                continue
            info = zipfile.ZipInfo(path.relative_to(source).as_posix(), (2024, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            output.writestr(info, path.read_bytes())
    return hashlib.sha256(target.read_bytes()).hexdigest()

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--legacy', action='store_true', help='显式重建历史包；本轮不使用')
    args = parser.parse_args()
    if args.legacy:
        digest = archive(ROOT / 'Demo/Web', ROOT / 'Demo/Resources/demo.zip')
        (ROOT / 'Demo/PackageDigest.h').write_text('// Generated by scripts/generate_demo.py\n#define OFT_DEMO_SHA256 @"' + digest + '"\n')
        print(digest)
    else:
        manifest = {}
        for label, version in [('A', 10000), ('B', 10001)]:
            source = ROOT / 'Demo/ManagedWeb' / label
            target = ROOT / 'Demo/Resources' / ('managed-' + label + '.zip')
            manifest[label] = {'version': version, 'sha256': archive(source, target), 'archive': target.relative_to(ROOT).as_posix()}
        (ROOT / 'Demo/ManagedPackageManifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
        print(json.dumps(manifest, indent=2))
